function findCatalogItem(symbol) {
  if (!symbol) return null;
  const upper = symbol.trim().toUpperCase();
  return (
    SYMBOL_CATALOG.find(
      (item) =>
        item.symbol.toUpperCase() === upper ||
        item.displaySymbol.toUpperCase() === upper
    ) || null
  );
}

function searchCatalog(query, market = 'all') {
  const q = (query || '').trim().toLowerCase();
  let items = SYMBOL_CATALOG;
  if (market && market !== 'all') {
    items = items.filter((i) => i.market === market);
  }
  if (!q) return items;

  const scored = [];
  for (const item of items) {
    let score = 0;
    const sym = item.symbol.toLowerCase();
    const disp = item.displaySymbol.toLowerCase();
    const name = item.name.toLowerCase();
    const enName = item.enName.toLowerCase();
    const koName = (item.koName || '').toLowerCase();

    if (sym === q || disp === q) score = 100;
    else if (item.aliases && item.aliases.some((a) => a.toLowerCase() === q)) score = 92;
    else if (sym.startsWith(q) || disp.startsWith(q)) score = 85;
    else if (name.includes(q) || (koName && koName.includes(q))) score = 78;
    else if (item.aliases && item.aliases.some((a) => a.toLowerCase().includes(q))) score = 70;
    else if (enName.includes(q) || sym.includes(q)) score = 60;

    if (score > 0) scored.push({ item, score });
  }
  scored.sort((a, b) => b.score - a.score);
  return scored.map((s) => s.item);
}

