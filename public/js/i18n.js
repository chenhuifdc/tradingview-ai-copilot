export function getLangPack(lang = 'zh-CN') {
  return DICT[lang] || DICT['zh-CN'];
}

export function getLangMeta(lang = 'zh-CN') {
  return SUPPORTED_LANGS.find((l) => l.code === lang) || SUPPORTED_LANGS[0];
}

/**
 * Dynamically translate a chart annotation label into the active chart language.
 * Works seamlessly for both structured labelKey items AND common LLM-returned terms.
 */
export function resolveChartLabel(item, lang = 'zh-CN') {
  if (!item) return '';
  const C = getLangPack(lang).chart;

  if (item.labelKey) {
    const val = C[item.labelKey];
    if (typeof val === 'function') {
      return val(item.labelCount ?? 1);
    }
    if (typeof val === 'string') {
      if (item.targetText) {
        return `${val} · ${C.target} ${item.targetText}`;
      }
      return val;
    }
  }

  // Fallback mapping for raw labels from external LLMs or older messages
  const raw = String(item.label || item.name || '').trim();
  if (!raw) return '';

  // For Bear Wick / Bull Wick keep concise standard chart wording or localized label
  if (item.kind === 'bear_wick' && /^bear\s*wick$/i.test(raw)) return C.bearWick;
  if (item.kind === 'bull_wick' && /^bull\s*wick$/i.test(raw)) return C.bullWick;

  return raw;
}
